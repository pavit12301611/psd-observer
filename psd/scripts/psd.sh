#!/usr/bin/env bash
# psd.sh — one entry point for installing, running and repairing PSD.
#
#   bash scripts/psd.sh install          user install: bin, notch extension, service
#   bash scripts/psd.sh install --with-deps   also install Fedora packages (sudo)
#   bash scripts/psd.sh service [install|restart|status|logs|stop]
#   bash scripts/psd.sh notch [install|repair|enable|reload|disable|status]
#   bash scripts/psd.sh whatsapp         print the exact agent .env lines
#   bash scripts/psd.sh url              the app link, for this PC and your phone
#   bash scripts/psd.sh doctor           what works, and the fix
#   bash scripts/psd.sh fix              install the missing desktop tools
#
# No git needed at runtime; the script only touches $HOME.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PREFIX="${PREFIX:-$HOME/.local}"
BINDIR="$PREFIX/bin"
SHAREDIR="$PREFIX/share/psd"
EXT_UUID="notch@pavit12301611.github.io"
EXTDIR="$PREFIX/share/gnome-shell/extensions/$EXT_UUID"
SCHEMADIR="$PREFIX/share/glib-2.0/schemas"
SERVICE_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"

c_reset=$'\033[0m'; c_dim=$'\033[2m'; c_ok=$'\033[32m'; c_warn=$'\033[33m'; c_bad=$'\033[31m'; c_b=$'\033[1m'
say()  { printf '%s\n' "$*"; }
ok()   { printf '%s✓%s %s\n' "$c_ok" "$c_reset" "$*"; }
warn() { printf '%s!%s %s\n' "$c_warn" "$c_reset" "$*"; }
bad()  { printf '%s✗%s %s\n' "$c_bad" "$c_reset" "$*"; }
head_() { printf '\n%s%s%s\n' "$c_b" "$*" "$c_reset"; }

need_node() {
  if ! command -v node >/dev/null 2>&1; then
    bad "node is not installed. Install Node 20+ (Fedora: sudo dnf install nodejs) and re-run."
    exit 1
  fi
  local major
  major="$(node -p 'process.versions.node.split(".")[0]')"
  if [ "$major" -lt 20 ]; then
    bad "Node $major is too old. PSD needs 20.19 or newer."
    exit 1
  fi
  ok "node $(node -v)"
}

install_deps() {
  head_ "Fedora packages"
  if ! command -v dnf >/dev/null 2>&1; then
    warn "dnf not found — skipping dependency install (this build targets Fedora)."
    return
  fi
  local packages=(
    nodejs glib2 libnotify
    grim wl-clipboard wmctrl ydotool wtype
    playerctl wireplumber
    gnome-shell gnome-extensions-app gobject-introspection gtk4 libadwaita
  )
  say "sudo dnf install -y ${packages[*]}"
  sudo dnf install -y "${packages[@]}" || warn "some packages failed; run 'bash scripts/psd.sh doctor' afterwards"
}

link_bin() {
  head_ "Command"
  mkdir -p "$BINDIR"
  rm -rf "$SHAREDIR"
  mkdir -p "$SHAREDIR"
  # Copy the runtime, not the docs/tests: the install stays small and obvious.
  for item in src web agents skills package.json README.md; do
    [ -e "$ROOT/$item" ] && cp -r "$ROOT/$item" "$SHAREDIR/"
  done
  mkdir -p "$SHAREDIR/scripts"
  cp "$ROOT/scripts/psd-phone-proxy.mjs" "$SHAREDIR/scripts/" 2>/dev/null || true
  cat > "$BINDIR/psd" <<EOF
#!/usr/bin/env bash
# Generated by psd.sh — runs the installed copy in $SHAREDIR
exec node "$SHAREDIR/src/cli.js" "\$@"
EOF
  chmod +x "$BINDIR/psd"
  # The phone's front door: same tree, no arguments to remember.
  cat > "$BINDIR/psd-proxy" <<EOF
#!/usr/bin/env bash
# Generated by psd.sh — the phone/desktop web app, with the token kept local.
exec node "$SHAREDIR/scripts/psd-phone-proxy.mjs" "\$@"
EOF
  chmod +x "$BINDIR/psd-proxy"
  ok "psd → $BINDIR/psd  ·  psd-proxy → $BINDIR/psd-proxy"
  case ":$PATH:" in
    *":$BINDIR:"*) ;;
    *) warn "$BINDIR is not on PATH. Add it:  export PATH=\"\$HOME/.local/bin:\$PATH\"" ;;
  esac
}

# Refuse to install an extension that GNOME Shell cannot load.
#
# This exists because of a real outage: the extension's lib/ was excluded by a
# `lib/` line in .gitignore, so a downloaded tree had extension.js importing
# modules that were not there. The Shell reported
#   "does not provide an export named: 'PSD_INTERFACE'"
# and disabled the whole extension. A missing file is cheap to detect — so
# detect it before touching the installed copy.
verify_extension() {
  local source="$1"
  local missing=0
  local file target
  while IFS= read -r file; do
    while IFS= read -r target; do
      local resolved
      resolved="$(cd "$(dirname "$file")" && cd "$(dirname "$target")" 2>/dev/null && pwd)/$(basename "$target")"
      if [ ! -f "$resolved" ]; then
        bad "$(basename "$file") imports $target, which is not in the download"
        missing=1
      fi
    done < <(grep -oE "from '(\.[^']+)'" "$file" 2>/dev/null | sed "s/from '//; s/'$//")
  done < <(find "$source" -name '*.js')
  for required in metadata.json extension.js prefs.js stylesheet.css \
      schemas/io.github.pavit12301611.Notch.gschema.xml \
      dbus/io.github.pavit12301611.Notch.xml \
      dbus/io.github.pavit12301611.Notch.Psd.xml; do
    [ -f "$source/$required" ] || { bad "missing $required"; missing=1; }
  done
  [ "$missing" = 0 ]
}

# Is the extension currently on disk loadable? Used to tell the owner their
# extension is broken before we start, and to confirm a repair afterwards.
installed_notch_healthy() {
  [ -d "$EXTDIR" ] || return 1
  verify_extension "$EXTDIR" >/dev/null 2>&1 || return 1
  if command -v node >/dev/null 2>&1 && [ -f "$ROOT/notch/tests/load.test.mjs" ]; then
    node "$ROOT/notch/tests/load.test.mjs" "$EXTDIR" >/dev/null 2>&1 || return 1
  fi
  return 0
}

install_notch() {
  head_ "Notch extension"
  if [ -d "$EXTDIR" ] && ! installed_notch_healthy; then
    warn "your installed extension is missing modules (this is the bug that shows"
    warn "'does not provide an export named: PSD_INTERFACE'). Repairing it now."
  fi
  local source="$ROOT/notch/extension"
  if [ ! -d "$source" ]; then
    warn "no notch/extension in this checkout — skipping (PSD works without the notch)."
    return
  fi
  if ! verify_extension "$source"; then
    bad "this download is incomplete — refusing to install a broken extension."
    say "   Your current extension has NOT been touched."
    say "   Fix: re-download the latest main, or report this at github.com/pavit12301611/psd-observer"
    return 1
  fi
  # Stronger check when node is available: load the modules the way the Shell
  # does, so a wrong export name is caught here instead of at login.
  if command -v node >/dev/null 2>&1 && [ -f "$source/../tests/load.test.mjs" ]; then
    if node "$source/../tests/load.test.mjs" "$source" >/dev/null 2>&1; then
      ok "modules load (imports resolve, exports present)"
    else
      bad "the extension's modules do not load:"
      node "$source/../tests/load.test.mjs" "$source" 2>&1 | sed 's/^/   /' | head -8
      say "   Your current extension has NOT been touched."
      return 1
    fi
  fi
  # And run it: enable() must survive a fake Shell, and every call into the
  # Shell must use an argument shape the Shell actually accepts. The errors
  # GNOME reports here only appear at runtime:
  #   Expected type string for argument 'path' but got type GObject.Object
  #   Unrecognized parameter "affectsInputRegion"
  # Both shipped past a passing build once. The suite is the gate now.
  if command -v node >/dev/null 2>&1 && [ -f "$source/../tests/enable.test.js" ]; then
    local gate=(
      tests/enable.test.js
      tests/gi-contract.test.js
      tests/shell-api.test.js
    )
    if ( cd "$source/.." && node --test "${gate[@]}" >/dev/null 2>&1 ); then
      ok "enable() and disable() run cleanly"
      ok "every Shell API the extension calls has the shape the Shell expects"
    else
      bad "the extension fails when enabled:"
      ( cd "$source/.." && node --test "${gate[@]}" 2>&1 ) |
        grep -E "^not ok|error:|AssertionError|Actual message" | head -8 | sed 's/^/   /'
      say "   Your current extension has NOT been touched."
      return 1
    fi
  fi
  ok "download is complete (all imported modules present)"
  # The owner may have the upstream extension installed already. Back it up,
  # then install this build over it: same UUID, so settings and position carry.
  if [ -d "$EXTDIR" ]; then
    local backup="$EXTDIR.backup-$(
      date +%s
    )"
    cp -r "$EXTDIR" "$backup"
    ok "existing extension backed up to $backup"
  fi
  mkdir -p "$EXTDIR" "$SCHEMADIR"
  # Install exactly this build, not this build on top of whatever was there.
  # A stale file left behind by an older version is how the Shell ended up
  # loading mismatched modules; lib/ is entirely ours.
  rm -rf "$EXTDIR/lib"
  cp -r "$source/." "$EXTDIR/"
  cp "$EXTDIR/schemas/"*.gschema.xml "$SCHEMADIR/"
  if command -v glib-compile-schemas >/dev/null 2>&1; then
    glib-compile-schemas "$SCHEMADIR" && ok "settings schema compiled"
  else
    warn "glib-compile-schemas missing (sudo dnf install glib2-devel)"
  fi
  # The Agent tab needs to know where PSD listens. Seed it once; the owner can
  # change it in Preferences → Agent.
  if command -v gsettings >/dev/null 2>&1; then
    local current url
    current="$(gsettings --schemadir "$SCHEMADIR" get io.github.pavit12301611.Notch psd-url 2>/dev/null || echo "''")"
    if [ "$current" = "''" ] || [ -z "$current" ]; then
      url="http://127.0.0.1:${PSD_PORT:-7788}"
      gsettings --schemadir "$SCHEMADIR" set io.github.pavit12301611.Notch psd-url "'$url'" || true
      ok "notch pointed at $url"
    fi
    # The agent page carries a conversation, so it needs more room than the
    # other tabs. Only nudge the values the owner has not chosen themselves.
    local width height
    width="$(gsettings --schemadir "$SCHEMADIR" get io.github.pavit12301611.Notch expanded-width 2>/dev/null || echo '')"
    height="$(gsettings --schemadir "$SCHEMADIR" get io.github.pavit12301611.Notch expanded-height 2>/dev/null || echo '')"
    if [ "$width" = "640" ] && [ "$height" = "480" ]; then
      gsettings --schemadir "$SCHEMADIR" set io.github.pavit12301611.Notch expanded-width 820 || true
      gsettings --schemadir "$SCHEMADIR" set io.github.pavit12301611.Notch expanded-height 560 || true
      ok "notch opened size set to 820x560 for the agent page"
    fi
  fi
  if installed_notch_healthy; then
    ok "extension installed and loadable at $EXTDIR"
  else
    bad "installed, but the extension still does not load — do not enable it."
    say "   Please report this with the output of: bash scripts/psd.sh notch status"
    return 1
  fi
  say "${c_dim}Log out and back in (Wayland cannot restart the Shell), then:${c_reset}"
  say "  gnome-extensions enable $EXT_UUID"
  say "  # or: bash scripts/psd.sh notch enable"
}

notch_cmd() {
  local action="${1:-install}"
  case "$action" in
    install) install_notch ;;
    enable)
      if ! command -v gnome-extensions >/dev/null 2>&1; then
        warn "gnome-extensions not found (sudo dnf install gnome-extensions-app)"
      else
        gnome-extensions enable "$EXT_UUID" && ok "notch enabled" || bad "enable failed — is the extension installed?"
      fi
      ;;
    disable) gnome-extensions disable "$EXT_UUID" && ok "notch disabled" ;;
    reload)
      if [ -n "${XDG_SESSION_TYPE:-}" ] && [ "${XDG_SESSION_TYPE}" = "wayland" ]; then
        warn "Wayland: log out and back in. There is no supported Shell reload."
      else
        gnome-extensions disable "$EXT_UUID" || true
        gnome-extensions enable "$EXT_UUID" && ok "notch reloaded"
      fi
      ;;
    status) gnome-extensions info "$EXT_UUID" ;;
    repair) install_notch ;;
    *) bad "unknown notch action: $action" ;;
  esac
}

install_service() {
  head_ "Service"
  need_node
  mkdir -p "$SERVICE_DIR"
  local unit="$SERVICE_DIR/psd-agent.service"
  local token="${PSD_TOKEN:-}"
  if [ -z "$token" ] && [ -f "${XDG_DATA_HOME:-$HOME/.local/share}/psd/token.txt" ]; then
    token="$(cat "${XDG_DATA_HOME:-$HOME/.local/share}/psd/token.txt")"
  fi
  cat > "$unit" <<EOF
[Unit]
Description=PSD — personal agent (notch, phone app, WhatsApp)
Documentation=file://$SHAREDIR/README.md
After=network-online.target

[Service]
Type=simple
WorkingDirectory=$SHAREDIR
Environment=NODE_ENV=production
Environment=PATH=$BINDIR:/usr/local/bin:/usr/bin:/bin
# PSD settings live in ~/.config/psd/env (optional, plain KEY=VALUE lines).
EnvironmentFile=-%h/.config/psd/env
ExecStart=$(command -v node) $SHAREDIR/src/index.js
Restart=on-failure
RestartSec=2
# The agent touches the session: screenshots, input, gsettings, the notch bus.
KillMode=mixed
TimeoutStopSec=10

[Install]
WantedBy=default.target
EOF
  if ! command -v systemctl >/dev/null 2>&1; then
    warn "no systemd --user here — run it yourself:  node $SHAREDIR/src/index.js"
    return
  fi
  systemctl --user daemon-reload || warn "systemctl daemon-reload failed"
  if systemctl --user enable --now psd-agent.service; then
    ok "psd-agent.service enabled and started"
    systemctl --user --no-pager --lines=0 status psd-agent.service | head -5 || true
  else
    warn "could not start the service — logs: journalctl --user -u psd-agent -n 40"
  fi
  if [ -n "$token" ]; then say "${c_dim}API token: $token${c_reset}"; fi
}

service_cmd() {
  local action="${1:-install}"
  case "$action" in
    install) install_service ;;
    restart) systemctl --user restart psd-agent.service && ok "restarted" ;;
    stop) systemctl --user stop psd-agent.service && ok "stopped" ;;
    status) systemctl --user --no-pager status psd-agent.service ;;
    logs) journalctl --user -u psd-agent.service -f ;;
    *) bad "unknown service action: $action" ;;
  esac
}

whatsapp_cmd() {
  head_ "Connect the WhatsApp agent to PSD"
  local token port
  port="$(node -e "import('$ROOT/src/config.js').then(m=>console.log(m.loadConfig().port))" 2>/dev/null || echo 7788)"
  token="$(node -e "import('$ROOT/src/config.js').then(m=>console.log(m.loadConfig().token))" 2>/dev/null || echo "")"
  say "Add these to whatsapp-agent/.env, then restart the agent:"
  say ""
  say "  ${c_b}# WhatsApp → PSD (same brain as the notch and the phone)${c_reset}"
  say "  LOCAL_API_URL=http://127.0.0.1:$port/v1"
  say "  LOCAL_MODEL=psd"
  say "  LOCAL_API_KEY=$token"
  say "  AI_PROVIDER=local"
  say ""
  say "  ${c_b}# optional: instant deterministic commands stay in the agent${c_reset}"
  say "  ${c_dim}# (PSD is used for anything the agent cannot do in one step)${c_reset}"
  say ""
  say "Verify from this PC (works even before WhatsApp restarts):"
  say "  curl -s -H 'content-type: application/json' -d '{\"text\":\"system status\"}' \\"
  say "       http://127.0.0.1:$port/psd/chat"
  say "  ${c_dim}# then in WhatsApp, ask it something only PSD can answer${c_reset}"
}

fix_cmd() {
  head_ "Repairing the desktop toolkit"
  install_deps
  if command -v systemctl >/dev/null 2>&1; then
    # ydotool needs its daemon for input on Wayland; harmless if already on.
    systemctl --user enable --now ydotool.service 2>/dev/null && ok "ydotool daemon on" || warn "ydotool daemon not started (input falls back to wtype)"
  fi
  bash "${BASH_SOURCE[0]}" doctor
}

doctor_cmd() {
  need_node
  node "$ROOT/src/cli.js" doctor
}

usage() {
  sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
}

main() {
  local command="${1:-install}"
  shift || true
  case "$command" in
    install)
      need_node
      for arg in "$@"; do
        case "$arg" in
          --with-deps) install_deps ;;
          --no-notch) NO_NOTCH=1 ;;
          --no-service) NO_SERVICE=1 ;;
          *) ;;
        esac
      done
      link_bin
      if [ "${NO_NOTCH:-0}" = "1" ]; then
        :
      elif ! install_notch; then
        NO_SERVICE="${NO_SERVICE:-0}"
      fi
      [ "${NO_SERVICE:-0}" = "1" ] || install_service
      head_ "Next"
      say "  psd doctor            what works here"
      say "  psd status            daemon, brain, surfaces"
      say "  psd url               the phone-app link (with its token)"
      say "  psd-proxy             the phone app one port up — the token stays on this PC"
      say "  bash scripts/psd.sh whatsapp   wire WhatsApp to this brain"
      ;;
    service) service_cmd "${1:-install}" ;;
    notch) notch_cmd "${1:-install}" ;;
    whatsapp) whatsapp_cmd ;;
    doctor) doctor_cmd ;;
    fix) fix_cmd ;;
    deps) install_deps ;;
    uninstall)
      head_ "Uninstall"
      systemctl --user disable --now psd-agent.service 2>/dev/null || true
      rm -f "$SERVICE_DIR/psd-agent.service"
      rm -rf "$SHAREDIR"
      rm -f "$BINDIR/psd"
      warn "kept: $EXTDIR (use 'gnome-extensions disable $EXT_UUID' or remove the folder)"
      warn "kept: ${XDG_DATA_HOME:-$HOME/.local/share}/psd (memory, token)"
      ok "removed"
      ;;
    url)
      node -e "import('$ROOT/src/config.js').then(m=>{const c=m.loadConfig();const t=c.token;const net=require('node:os').networkInterfaces();const ips=Object.values(net).flat().filter(a=>a&&a.family==='IPv4'&&!a.internal).map(a=>a.address);console.log('app      http://127.0.0.1:'+c.port+'/?token='+t);for(const ip of ips)console.log('phone    http://'+ip+':'+c.port+'/?token='+t);console.log('proxy    psd-proxy   (then http://<this-pc>:'+(c.port+1)+' — no token in the URL)');})"
      ;;
    -h|--help|help|*) usage ;;
  esac
}

main "$@"
